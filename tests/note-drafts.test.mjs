import assert from 'node:assert/strict';
import vm from 'node:vm';
import { readFileSync } from 'node:fs';
const context=vm.createContext({});
vm.runInContext(readFileSync('frontend/js/note-drafts.js','utf8')+';globalThis.factory=NoteDraftStore;',context);
const map=new Map(), storage={ getItem:k=>map.get(k), setItem:(k,v)=>map.set(k,v), removeItem:k=>map.delete(k) };
const calls=[];
const drafts=context.factory.create({storage,save:(p,n,data)=>new Promise((resolve,reject)=>calls.push({p,n,data,resolve,reject}))});
const tick=()=>new Promise(r=>setImmediate(r));
const original={id:'n1',title:'Title',content:'initial'};
const entry=drafts.open('p1',original);
drafts.change(entry,{title:'Title',content:'first'});
const first=drafts.save(entry); await tick();
drafts.change(entry,{title:'Title',content:'latest'});
const latest=drafts.save(entry); await tick();
assert.equal(calls.length,1,'same note writes are serialized');
calls[0].resolve({...original,content:'first'}); await first; await tick();
assert.equal(entry.dirty,true,'old response cannot mark new edits saved');
assert.equal(JSON.parse([...map.values()][0]).content,'latest');
assert.equal(calls.length,2);
calls[1].resolve({...original,content:'latest'}); await latest;
assert.equal(entry.dirty,false); assert.equal(map.size,0);
assert.equal(drafts.open('p1',original).data.content,'latest','stale list entry cannot replace a successful background save');
const readVersion=drafts.version();
drafts.open('p1',{...original,content:'fresh GET'},readVersion);
assert.equal(entry.data.content,'fresh GET','fresh list can refresh a clean entry');
drafts.change(entry,{title:'Title',content:'edited after GET started'});
drafts.open('p1',original,readVersion);
assert.equal(entry.data.content,'edited after GET started','late GET cannot replace local edits');
drafts.change(entry,{title:'Title',content:'offline draft'});
const failure=drafts.save(entry); await tick(); calls[2].reject(Error('offline')); await failure;
assert.equal(entry.dirty,true); assert.equal(map.size,1);
const reopened=context.factory.create({storage,save:async(p,n,data)=>({...original,...data})}).open('p1',original);
assert.equal(reopened.data.content,'offline draft'); assert.equal(reopened.recovered,true);
const other=drafts.open('p2',{...original,id:'n2'});
drafts.change(other,{title:'Other',content:'other document'});
const saveOther=drafts.save(other); await tick();
assert.equal(calls[3].p,'p2'); assert.equal(entry.data.content,'offline draft');
calls[3].resolve({...original,id:'n2',content:'other document'}); await saveOther;
const retry=drafts.save(entry); await tick(); calls[4].resolve({...original,content:'offline draft'}); await retry;
assert.equal(entry.dirty,false);
drafts.discard(entry); assert.equal(drafts.get('p1','n1'),undefined);
const blocked=context.factory.create({storage:{getItem(){},setItem(){throw Error('quota')},removeItem(){}},save:async()=>original});
const quota=blocked.open('p1',original); blocked.change(quota,{title:'x',content:'x'});
assert.equal(quota.storageError,true,'storage failure is surfaced');
console.log('PASS note queues, late responses, durable drafts, retry, owner isolation and quota handling');
