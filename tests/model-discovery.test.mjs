import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require=createRequire(import.meta.url);
const {create}=require('../frontend/js/model-discovery');
let time=0;const scheduled=new Map();let seq=0;
const timers={setTimeout:fn=>{scheduled.set(++seq,fn);return seq;},clearTimeout:id=>scheduled.delete(id)};
const flush=async()=>{const callbacks=[...scheduled.values()];scheduled.clear();for(const fn of callbacks)await fn();};
const calls=[],events=[];
const discovery=create({timers,now:()=>time,onChange:id=>events.push(id),request:async body=>{calls.push(body);return {ok:true,models:['model-b','model-a','model-a','<model>',null,42]};}});
const input={id:'one',baseURL:'https://api.example/v1/',key:'sk-fictional-123'};
discovery.schedule({});await flush();assert.equal(calls.length,0);
discovery.schedule({...input,key:''});await flush();assert.equal(calls.length,0);
discovery.schedule({...input,baseURL:'file:///bad'});await flush();assert.equal(calls.length,0);
discovery.schedule(input);discovery.schedule(input);discovery.schedule({...input,key:'new-fictional-key'});
assert.equal(scheduled.size,1);await flush();assert.equal(calls.length,1);
assert.deepEqual(discovery.get('one').models,['model-b','model-a','<model>']);
assert.equal(calls[0].api_key,'new-fictional-key');
discovery.schedule({...input,key:'new-fictional-key'});await flush();assert.equal(calls.length,1);
time=300001;discovery.schedule({...input,key:'new-fictional-key'});await flush();assert.equal(calls.length,2);
assert.ok(!JSON.stringify(discovery.get('one')).includes('fictional'));
discovery.forget('one');assert.deepEqual(discovery.get('one').models,[]);
console.log('PASS prerequisites, debouncing, credential changes, deduplication, cache expiry and secret-free public state');

let complete;const pending=new Promise(r=>complete=r);const late=[];let aborted=false;
const race=create({timers,onChange:id=>late.push(id),request:(_body,{signal})=>{signal.addEventListener('abort',()=>aborted=true);return pending;}});
race.schedule(input);const running=flush();
race.schedule({...input,id:'two',baseURL:'https://other.example/v1'});
assert.equal(aborted,true);complete({ok:true,models:['obsolete-model']});await running;
assert.equal(race.get('one').status,'loading','obsolete completion does not alter old profile');
assert.deepEqual(race.get('two').models,[]);
race.cancel();await flush();
let attempts=0;
const failure=create({timers,now:()=>time,request:async()=>{attempts++;throw Error('private diagnostic');}});
failure.schedule(input);await flush();assert.equal(failure.get('one').status,'unavailable');
assert.ok(!failure.get('one').message.includes('private'));
failure.schedule(input);await flush();assert.equal(attempts,1);
time+=60001;failure.schedule(input);await flush();assert.equal(attempts,2);
console.log('PASS profile switch cancellation, stale-response rejection and quiet failure backoff');
