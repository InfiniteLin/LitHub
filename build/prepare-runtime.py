"""Stage a smaller runtime for shipping; never change the dependency source tree."""
import argparse
import json
from pathlib import Path
import shutil
import subprocess
import time

MARKER = '.lithub-runtime-stage'
# Keep runtime helpers such as numpy.testing, scipy._lib and all package metadata/licenses.
TEST_PACKAGES = {'numpy', 'scipy', 'pandas', 'onnx', 'networkx', 'shapely',
                 'colorama', 'fsspec', 'freetype', 'certifi', 'regex', 'skimage'}


def excluded(relative: Path) -> str | None:
    parts = relative.parts
    if '__pycache__' in parts or relative.suffix in {'.pyc', '.pyo'}:
        return 'bytecode'
    if parts[:2] == ('Lib', 'site-packages') and len(parts) > 2:
        package = parts[2]
        if package == 'pip' or (package.startswith('pip-') and package.endswith('.dist-info')):
            return 'pip'
        if package in {'gradio', 'gradio_client'}:
            return 'unused_gui'
        if package in TEST_PACKAGES and any(part in {'tests', 'test'} for part in parts[3:]):
            return 'tests'
        if package == 'bin' and relative.name.lower().startswith('pip'):
            return 'pip'
    return None


def prepare(source: Path, destination: Path, verify: bool = True) -> dict:
    source, destination = source.resolve(), destination.resolve()
    if source == destination or source.is_relative_to(destination) or destination.is_relative_to(source):
        raise ValueError('Source and staging directories must be separate, non-nested folders')
    if not (source / 'python.exe').is_file():
        raise ValueError('Source is not a bundled Windows Python runtime')
    marker = destination / MARKER
    if destination.exists() and any(destination.iterdir()) and not marker.is_file():
        raise ValueError('Refusing to modify an existing directory without the staging marker')
    destination.mkdir(parents=True, exist_ok=True)
    marker.write_text('Generated by build/prepare-runtime.py\n', encoding='utf8')
    expected = {MARKER}
    report = {'source_files': 0, 'source_bytes': 0, 'staged_files': 0, 'staged_bytes': 0, 'excluded': {}}
    for item in source.rglob('*'):
        if item.is_symlink():
            raise ValueError(f'Unexpected runtime symlink: {item}')
        if not item.is_file():
            continue
        relative, size = item.relative_to(source), item.stat().st_size
        report['source_files'] += 1
        report['source_bytes'] += size
        reason = excluded(relative)
        # A standalone sourceless module can be legitimate. Only strip its bytecode when source exists.
        if reason == 'bytecode' and '__pycache__' not in relative.parts and not item.with_suffix('.py').exists():
            reason = None
        if reason:
            bucket = report['excluded'].setdefault(reason, {'files': 0, 'bytes': 0})
            bucket['files'] += 1
            bucket['bytes'] += size
            continue
        target = destination / relative
        if target.is_symlink() or any(parent.is_symlink() for parent in target.parents if parent != destination.parent):
            raise ValueError(f'Unexpected staging symlink: {target}')
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or target.stat().st_size != size or target.stat().st_mtime_ns != item.stat().st_mtime_ns:
            shutil.copy2(item, target)
        expected.add(relative.as_posix())
        report['staged_files'] += 1
        report['staged_bytes'] += size
    # Remove stale generated files only inside the resolved, marked staging directory.
    for item in sorted(destination.rglob('*'), key=lambda p: len(p.parts), reverse=True):
        if item.is_symlink():
            raise ValueError(f'Unexpected staging symlink: {item}')
        if item.is_file() and item.relative_to(destination).as_posix() not in expected:
            item.unlink()
        elif item.is_dir() and not any(item.iterdir()):
            item.rmdir()
    if verify:
        verify_runtime(destination)
    return report


def verify_runtime(runtime: Path):
    python = runtime / 'python.exe'
    existing_bytecode = set(runtime.rglob('*.pyc'))
    code = '''
import fastapi, uvicorn, pydantic, multipart, pypdf, pymupdf, openai
import numpy as np, scipy.linalg, pandas, cv2, onnx, onnxruntime, skimage, networkx
from importlib.metadata import version
assert np.allclose(scipy.linalg.solve([[2.,0.],[0.,2.]], [2.,4.]), [1.,2.])
assert cv2.resize(np.zeros((4,4),dtype=np.uint8),(2,2)).shape == (2,2)
assert pandas.DataFrame({'a':[1,2]}).a.sum() == 3
assert onnxruntime.get_available_providers()
assert version('pdf2zh') == '1.9.11'
doc=pymupdf.open(); page=doc.new_page(); page.insert_text((72,72),'Runtime verification')
assert 'Runtime verification' in page.get_text(); doc.close()
print('PASS staged runtime: backend, scientific/native libraries, PDF rendering and package metadata')
'''
    flags = getattr(subprocess, 'CREATE_NO_WINDOW', 0)
    subprocess.run([str(python), '-B', '-c', code], check=True, creationflags=flags, timeout=90)
    cli = Path(__file__).resolve().parents[1] / 'backend' / 'pdf2zh_cli.py'
    subprocess.run([str(python), '-B', str(cli), '--help'], check=True,
                   stdout=subprocess.DEVNULL, creationflags=flags, timeout=90)
    if set(runtime.rglob('*.pyc')) - existing_bytecode:
        raise RuntimeError('Runtime verification unexpectedly created bytecode')
    print('PASS staged runtime: complete pdf2zh command line import chain')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    project = Path(__file__).resolve().parents[1]
    parser.add_argument('--source', type=Path, default=project / 'build/python')
    parser.add_argument('--destination', type=Path, default=project / 'build/runtime')
    parser.add_argument('--report', type=Path, default=project / 'build/runtime-report.json')
    args = parser.parse_args()
    started = time.monotonic()
    result = prepare(args.source, args.destination)
    result['seconds'] = round(time.monotonic() - started, 2)
    args.report.write_text(json.dumps(result, indent=2), encoding='utf8')
    print(json.dumps(result, indent=2))
